CREATE TABLE LOAN_CLOSURE_REQUEST ( 

    CLOSURE_REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    LOAN_ID NUMBER NOT NULL, 

    OFFICER_ID NUMBER, 

    REQUEST_DATE DATE DEFAULT SYSDATE NOT NULL, 

    CLOSURE_TYPE VARCHAR2(30) NOT NULL, 

    STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL, 

    REASON VARCHAR2(1000), 

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

  

    CONSTRAINT FK_CLOSURE_LOAN 

    FOREIGN KEY (LOAN_ID) 

    REFERENCES LOAN_ACCOUNT(LOAN_ID), 

  

    CONSTRAINT FK_CLOSURE_OFFICER 

    FOREIGN KEY (OFFICER_ID) 

    REFERENCES OFFICER(OFFICER_ID), 

  

    CONSTRAINT CHK_CLOSURE_TYPE 

    CHECK (CLOSURE_TYPE IN ( 

        'NORMAL', 

        'FORECLOSURE', 

        'PREPAYMENT' 

    )), 

  

    CONSTRAINT CHK_CLOSURE_STATUS 

    CHECK (STATUS IN ( 

        'PENDING', 

        'UNDER_REVIEW', 

        'APPROVED', 

        'REJECTED', 

        'PAYMENT_PENDING', 

        'COMPLETED', 

        'CANCELLED' 

    )) 

); 

  

CREATE INDEX IDX_CLOSURE_LOAN 

ON LOAN_CLOSURE_REQUEST (LOAN_ID); 

  

CREATE INDEX IDX_CLOSURE_OFFICER 

ON LOAN_CLOSURE_REQUEST (OFFICER_ID); 

  

CREATE INDEX IDX_CLOSURE_STATUS 

ON LOAN_CLOSURE_REQUEST (STATUS); 

  

