-- Run in SQL Developer with F5, connected as the owner of LOAN_ACCOUNT/NOC.
-- Includes CREATE TABLE for both NOC and NOC_AUDIT when absent, and ALTER TABLE
-- for an existing legacy NOC. LOAN_ACCOUNT must already exist in this schema.
-- Stop NOC Service first. Oracle DDL commits implicitly; back up the schema first.
-- This script adds missing objects only. It does not drop/reset existing records,
-- fabricate PDF hashes, issue certificates, or mark legacy certificates AVAILABLE.
-- If a column/table already exists, its definition and data are preserved.
DECLARE
    object_count NUMBER;

    PROCEDURE add_noc_column(column_name_in VARCHAR2, definition_in VARCHAR2) IS
        column_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO column_count FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'NOC' AND COLUMN_NAME = column_name_in;
        IF column_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE NOC ADD (' || column_name_in || ' ' || definition_in || ')';
        END IF;
    END;
BEGIN
    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'LOAN_ACCOUNT';
    IF object_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'LOAN_ACCOUNT not found. Connect as its owner before running this migration.');
    END IF;

    -- 1. NOC: create the full table for a fresh schema, or extend the old table below.
    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'NOC';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE NOC (
            NOC_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            LOAN_ID NUMBER NOT NULL,
            CERTIFICATE_NUMBER VARCHAR2(100) UNIQUE NOT NULL,
            ISSUE_DATE DATE DEFAULT SYSDATE NOT NULL,
            FILE_PATH VARCHAR2(500),
            FILE_HASH VARCHAR2(64),
            NOC_STATUS VARCHAR2(30) DEFAULT ''GENERATION_PENDING'' NOT NULL,
            VERSION_NUMBER NUMBER(10) DEFAULT 1 NOT NULL,
            GENERATED_AT TIMESTAMP,
            ISSUED_BY NUMBER(19),
            REMARKS VARCHAR2(1000),
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT FK_NOC_LOAN FOREIGN KEY (LOAN_ID) REFERENCES LOAN_ACCOUNT(LOAN_ID)
        )';
    END IF;

    add_noc_column('FILE_HASH', 'VARCHAR2(64)');
    add_noc_column('GENERATED_AT', 'TIMESTAMP');
    add_noc_column('ISSUED_BY', 'NUMBER(19)');
    add_noc_column('REMARKS', 'VARCHAR2(1000)');
    add_noc_column('VERSION_NUMBER', 'NUMBER(10) DEFAULT 1 NOT NULL');

    SELECT COUNT(*) INTO object_count FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'NOC' AND COLUMN_NAME = 'NOC_STATUS';
    IF object_count = 0 THEN
        -- Old seeded records have no verified PDF/hash: allow authorized retry,
        -- rather than pretending they are downloadable certificates.
        EXECUTE IMMEDIATE 'ALTER TABLE NOC ADD (NOC_STATUS VARCHAR2(30) DEFAULT ''FAILED'' NOT NULL)';
        EXECUTE IMMEDIATE 'ALTER TABLE NOC MODIFY (NOC_STATUS DEFAULT ''GENERATION_PENDING'')';
    END IF;

    -- 2. NOC_AUDIT: preserve an existing audit table and its history.
    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'NOC_AUDIT';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE NOC_AUDIT (
            AUDIT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            NOC_ID NUMBER(19) NOT NULL,
            ACTION VARCHAR2(100) NOT NULL,
            ACTOR_ID NUMBER(19),
            ACTION_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            REMARKS VARCHAR2(1000),
            CONSTRAINT FK_NOC_AUDIT_NOC FOREIGN KEY (NOC_ID) REFERENCES NOC(NOC_ID)
        )';
    END IF;

    -- Separate guard also allows rerunning after table creation but index failure.
    SELECT COUNT(*) INTO object_count FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_NOC_AUDIT_NOC_TIME';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_NOC_AUDIT_NOC_TIME ON NOC_AUDIT (NOC_ID, ACTION_AT)';
    END IF;
END;
/

-- Verify definitions. Existing objects with incompatible types need separate review;
-- this migration deliberately does not rewrite their definitions.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS WHERE TABLE_NAME IN ('NOC', 'NOC_AUDIT')
ORDER BY TABLE_NAME, COLUMN_ID;
