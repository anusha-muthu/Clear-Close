CREATE TABLE GRIEVANCES (
    GRIEVANCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOAN_ACCOUNT_ID NUMBER NOT NULL,
    BORROWER_ID NUMBER NOT NULL,
    CATEGORY VARCHAR2(30) NOT NULL,
    DESCRIPTION VARCHAR2(1000) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    ASSIGNED_TO NUMBER,
    RESOLUTION_REMARKS VARCHAR2(1000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    
    CONSTRAINT FK_GRIEVANCES_LOAN
    FOREIGN KEY (LOAN_ACCOUNT_ID)
    REFERENCES LOAN_ACCOUNT(LOAN_ID),
    
    CONSTRAINT FK_GRIEVANCES_BORROWER
    FOREIGN KEY (BORROWER_ID)
    REFERENCES APP_USERS(USER_ID),
    
    CONSTRAINT CHK_GRIEVANCES_STATUS CHECK (
        STATUS IN (
            'OPEN', 'IN_PROGRESS', 'RESOLVED',
            'ESCALATED', 'CLOSED'
        )
    )
);

commit;
