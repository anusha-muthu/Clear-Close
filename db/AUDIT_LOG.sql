
CREATE TABLE AUDIT_LOG (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER,
    OFFICER_ID NUMBER,
    ENTITY_ID NUMBER NOT NULL,
    ENTITY_TYPE VARCHAR2(50) NOT NULL,
    ACTION VARCHAR2(100) NOT NULL,
    ACTION_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DETAILS VARCHAR2(1000),

    PAYMENT_ID NUMBER,
    QUOTE_ID NUMBER,
    EXIT_REQUEST_ID NUMBER,
    CLOSURE_REQUEST_ID NUMBER,
    NOC_ID NUMBER,
    GRIEVANCE_ID NUMBER,
    RELEASE_REQUEST_ID NUMBER,

    CONSTRAINT FK_AUDIT_USER
        FOREIGN KEY (USER_ID)
        REFERENCES BORROWERS(USER_ID),

    CONSTRAINT FK_AUDIT_OFFICER
        FOREIGN KEY (OFFICER_ID)
        REFERENCES OFFICER(OFFICER_ID),

    CONSTRAINT FK_AUDIT_PAYMENT
        FOREIGN KEY (PAYMENT_ID)
        REFERENCES PAYMENT(PAYMENT_ID),

    CONSTRAINT FK_AUDIT_QUOTE
        FOREIGN KEY (QUOTE_ID)
        REFERENCES SETTLEMENT_QUOTE(QUOTE_ID),

    CONSTRAINT FK_AUDIT_EXIT
        FOREIGN KEY (EXIT_REQUEST_ID)
        REFERENCES COOLING_OFF_REQUEST(EXIT_REQUEST_ID),

    CONSTRAINT FK_AUDIT_CLOSURE
        FOREIGN KEY (CLOSURE_REQUEST_ID)
        REFERENCES LOAN_CLOSURE_REQUEST(CLOSURE_REQUEST_ID),

    CONSTRAINT FK_AUDIT_NOC
        FOREIGN KEY (NOC_ID)
        REFERENCES NOC(NOC_ID),

    CONSTRAINT FK_AUDIT_GRIEVANCE
        FOREIGN KEY (GRIEVANCE_ID)
        REFERENCES GRIEVANCES(GRIEVANCE_ID),

    CONSTRAINT FK_AUDIT_RELEASE
        FOREIGN KEY (RELEASE_REQUEST_ID)
        REFERENCES COLLATERAL_RELEASE_REQUESTS(REQUEST_ID),

    CONSTRAINT CHK_AUDIT_ENTITY_TYPE CHECK (
        ENTITY_TYPE IN (
            'PAYMENT',
            'SETTLEMENT_QUOTE',
            'COOLING_OFF_REQUEST',
            'LOAN_CLOSURE_REQUEST',
            'NOC',
            'GRIEVANCE',
            'COLLATERAL_RELEASE_REQUEST',
            'OFFICER'
        )
    ),

    CONSTRAINT CHK_AUDIT_ENTITY_REF CHECK (
        (
            ENTITY_TYPE = 'PAYMENT'
            AND PAYMENT_ID IS NOT NULL
            AND PAYMENT_ID = ENTITY_ID
        )
        OR (
            ENTITY_TYPE = 'SETTLEMENT_QUOTE'
            AND QUOTE_ID IS NOT NULL
            AND QUOTE_ID = ENTITY_ID
        )
        OR (
            ENTITY_TYPE = 'COOLING_OFF_REQUEST'
            AND EXIT_REQUEST_ID IS NOT NULL
            AND EXIT_REQUEST_ID = ENTITY_ID
        )
        OR (
            ENTITY_TYPE = 'LOAN_CLOSURE_REQUEST'
            AND CLOSURE_REQUEST_ID IS NOT NULL
            AND CLOSURE_REQUEST_ID = ENTITY_ID
        )
        OR (
            ENTITY_TYPE = 'NOC'
            AND NOC_ID IS NOT NULL
            AND NOC_ID = ENTITY_ID
        )
        OR (
            ENTITY_TYPE = 'GRIEVANCE'
            AND GRIEVANCE_ID IS NOT NULL
            AND GRIEVANCE_ID = ENTITY_ID
        )
        OR (
            ENTITY_TYPE = 'COLLATERAL_RELEASE_REQUEST'
            AND RELEASE_REQUEST_ID IS NOT NULL
            AND RELEASE_REQUEST_ID = ENTITY_ID
        )
        OR (
            ENTITY_TYPE = 'OFFICER'
            AND OFFICER_ID IS NOT NULL
            AND OFFICER_ID = ENTITY_ID
        )
    )
);

CREATE INDEX IDX_AUDIT_USER
    ON AUDIT_LOG(USER_ID);

CREATE INDEX IDX_AUDIT_OFFICER
    ON AUDIT_LOG(OFFICER_ID);

CREATE INDEX IDX_AUDIT_ENTITY
    ON AUDIT_LOG(ENTITY_TYPE, ENTITY_ID);

CREATE INDEX IDX_AUDIT_PAYMENT
    ON AUDIT_LOG(PAYMENT_ID);

CREATE INDEX IDX_AUDIT_QUOTE
    ON AUDIT_LOG(QUOTE_ID);

CREATE INDEX IDX_AUDIT_EXIT
    ON AUDIT_LOG(EXIT_REQUEST_ID);

CREATE INDEX IDX_AUDIT_CLOSURE
    ON AUDIT_LOG(CLOSURE_REQUEST_ID);

CREATE INDEX IDX_AUDIT_NOC
    ON AUDIT_LOG(NOC_ID);

CREATE INDEX IDX_AUDIT_GRIEVANCE
    ON AUDIT_LOG(GRIEVANCE_ID);

CREATE INDEX IDX_AUDIT_RELEASE
    ON AUDIT_LOG(RELEASE_REQUEST_ID);

CREATE INDEX IDX_AUDIT_ACTION_TIME
    ON AUDIT_LOG(ACTION_TIME);

