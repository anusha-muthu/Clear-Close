CREATE TABLE PAYMENT ( 

    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    QUOTE_ID NUMBER NOT NULL, 

    RAZORPAY_PAYMENT_ID VARCHAR2(100) UNIQUE, 

    AMOUNT NUMBER(15,2) NOT NULL, 

    PAYMENT_STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL, 

    PAYMENT_DATE DATE, 

    METHOD VARCHAR2(30), 

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

  

    CONSTRAINT FK_PAYMENT_QUOTE 

    FOREIGN KEY (QUOTE_ID) 

    REFERENCES SETTLEMENT_QUOTE(QUOTE_ID), 

  

    CONSTRAINT CHK_PAYMENT_STATUS CHECK ( 

        PAYMENT_STATUS IN ( 

            'PENDING', 'INITIATED', 'SUCCESS', 

            'FAILED', 'REFUNDED', 'CANCELLED' 

        ) 

    ), 

  

    CONSTRAINT CHK_PAYMENT_METHOD CHECK ( 

        METHOD IN ( 

            'UPI', 'NET_BANKING', 'DEBIT_CARD', 

            'CREDIT_CARD', 'NEFT', 'RTGS', 'IMPS' 

        ) 

    ), 

  

    CONSTRAINT CHK_PAYMENT_AMOUNT CHECK ( 

        AMOUNT > 0 

    ) 

); 

  

CREATE INDEX IDX_PAYMENT_QUOTE 

ON PAYMENT (QUOTE_ID); 

  

CREATE INDEX IDX_PAYMENT_STATUS 

ON PAYMENT (PAYMENT_STATUS); 

  

CREATE INDEX IDX_PAYMENT_DATE 

ON PAYMENT (PAYMENT_DATE); 

  

