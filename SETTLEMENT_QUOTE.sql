CREATE TABLE SETTLEMENT_QUOTE ( 

    QUOTE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    LOAN_ID NUMBER NOT NULL, 

    EXIT_REQUEST_ID NUMBER, 

    CLOSURE_REQUEST_ID NUMBER, 

    QUOTE_TYPE VARCHAR2(30) NOT NULL, 

    PRINCIPAL_AMOUNT NUMBER(15,2) NOT NULL, 

    INTEREST_AMOUNT NUMBER(15,2) DEFAULT 0 NOT NULL, 

    CHARGES_AMOUNT NUMBER(15,2) DEFAULT 0 NOT NULL, 

    TAX_AMOUNT NUMBER(15,2) DEFAULT 0 NOT NULL, 

    TOTAL_AMOUNT NUMBER(15,2) NOT NULL, 

    VALID_UNTIL DATE NOT NULL, 

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

  

    CONSTRAINT FK_QUOTE_LOAN 

    FOREIGN KEY (LOAN_ID) 

    REFERENCES LOAN_ACCOUNT(LOAN_ID), 

  

    CONSTRAINT FK_QUOTE_EXIT 

    FOREIGN KEY (EXIT_REQUEST_ID) 

    REFERENCES COOLING_OFF_REQUEST(EXIT_REQUEST_ID), 

  

    CONSTRAINT FK_QUOTE_CLOSURE 

    FOREIGN KEY (CLOSURE_REQUEST_ID) 

    REFERENCES LOAN_CLOSURE_REQUEST(CLOSURE_REQUEST_ID), 

  

    CONSTRAINT CHK_QUOTE_TYPE CHECK ( 

        QUOTE_TYPE IN ('COOLING_OFF', 'CLOSURE') 

    ), 

  

    CONSTRAINT CHK_QUOTE_REQUEST CHECK ( 

        (QUOTE_TYPE = 'COOLING_OFF' 

         AND EXIT_REQUEST_ID IS NOT NULL 

         AND CLOSURE_REQUEST_ID IS NULL) 

        OR 

        (QUOTE_TYPE = 'CLOSURE' 

         AND CLOSURE_REQUEST_ID IS NOT NULL 

         AND EXIT_REQUEST_ID IS NULL) 

    ), 

  

    CONSTRAINT CHK_QUOTE_AMOUNT CHECK ( 

        PRINCIPAL_AMOUNT >= 0 

        AND INTEREST_AMOUNT >= 0 

        AND CHARGES_AMOUNT >= 0 

        AND TAX_AMOUNT >= 0 

        AND TOTAL_AMOUNT = 

            PRINCIPAL_AMOUNT + INTEREST_AMOUNT + 

            CHARGES_AMOUNT + TAX_AMOUNT 

    ) 

); 

  

CREATE INDEX IDX_QUOTE_LOAN 

ON SETTLEMENT_QUOTE (LOAN_ID); 

  

CREATE INDEX IDX_QUOTE_EXIT 

ON SETTLEMENT_QUOTE (EXIT_REQUEST_ID); 

  

CREATE INDEX IDX_QUOTE_CLOSURE 

ON SETTLEMENT_QUOTE (CLOSURE_REQUEST_ID); 

  

