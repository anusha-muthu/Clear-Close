CREATE TABLE if not EXISTS OFFICER (
    OFFICER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER,
    FULL_NAME VARCHAR2(150) NOT NULL,
    USERNAME VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PAN_CARD VARCHAR2(10) UNIQUE,
    ROLE VARCHAR2(30) NOT NULL,
    LOCATION VARCHAR2(150),
    ACCOUNT_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_OFFICER_USER
        FOREIGN KEY (USER_ID)
        REFERENCES BORROWERS(USER_ID),

    CONSTRAINT UQ_OFFICER_USER UNIQUE (USER_ID),

    CONSTRAINT CHK_OFFICER_ROLE CHECK (
        ROLE IN (
            'LOAN_CLOSURE_OFFICER',
            'GRIEVANCE_OFFICER',
            'COLLATERAL_OFFICER',
            'ADMIN'
        )
    ),

    CONSTRAINT CHK_OFFICER_STATUS CHECK (
        ACCOUNT_STATUS IN ('ACTIVE', 'LOCKED', 'DISABLED')
    ),

    CONSTRAINT CHK_OFFICER_PAN CHECK (
        PAN_CARD IS NULL
        OR REGEXP_LIKE(PAN_CARD, '^[A-Z]{5}[0-9]{4}[A-Z]$')
    )
);

