CREATE TABLE LOAN_PRODUCT_RULE (
    RULE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_TYPE VARCHAR2(50) NOT NULL,
    COOLING_OFF_DAYS NUMBER(4) DEFAULT 0 NOT NULL,
    EARLY_CLOSURE_ALLOWED CHAR(1) DEFAULT 'Y' NOT NULL,
    CLOSURE_CHARGE_TYPE VARCHAR2(20) DEFAULT 'NONE' NOT NULL,
    CLOSURE_CHARGE_VALUE NUMBER(12,2) DEFAULT 0 NOT NULL,
    NOC_REQUIRES_FULL_SETTLEMENT CHAR(1) DEFAULT 'Y' NOT NULL,
    COLLATERAL_RELEASE_REQUIRES_CLOSURE CHAR(1) DEFAULT 'Y' NOT NULL,
    EFFECTIVE_FROM DATE DEFAULT SYSDATE NOT NULL,
    EFFECTIVE_TO DATE,
    RULE_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT UQ_RULE_PRODUCT_START
        UNIQUE (PRODUCT_TYPE, EFFECTIVE_FROM),

    CONSTRAINT CHK_COOLING_DAYS
        CHECK (COOLING_OFF_DAYS >= 0),

    CONSTRAINT CHK_EARLY_CLOSURE
        CHECK (EARLY_CLOSURE_ALLOWED IN ('Y', 'N')),

    CONSTRAINT CHK_CLOSURE_CHARGE_TYPE
        CHECK (CLOSURE_CHARGE_TYPE IN (
            'NONE', 'FIXED', 'PERCENTAGE'
        )),

    CONSTRAINT CHK_CLOSURE_CHARGE_VALUE
        CHECK (CLOSURE_CHARGE_VALUE >= 0),

    CONSTRAINT CHK_NOC_SETTLEMENT
        CHECK (NOC_REQUIRES_FULL_SETTLEMENT IN ('Y', 'N')),

    CONSTRAINT CHK_COLLATERAL_CLOSURE
        CHECK (COLLATERAL_RELEASE_REQUIRES_CLOSURE IN ('Y', 'N')),

    CONSTRAINT CHK_RULE_DATES
        CHECK (
            EFFECTIVE_TO IS NULL
            OR EFFECTIVE_TO >= EFFECTIVE_FROM
        ),

    CONSTRAINT CHK_RULE_STATUS
        CHECK (RULE_STATUS IN ('ACTIVE', 'INACTIVE'))
);
