CREATE TABLE LOAN_ACCOUNT (
    loan_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_id         NUMBER NOT NULL,
    rule_id             NUMBER NOT NULL,
    loan_reference      VARCHAR2(50) NOT NULL UNIQUE,
    principal_amount    NUMBER(15,2) NOT NULL,
    outstanding_amount  NUMBER(15,2) NOT NULL,
    interest_rate       NUMBER(7,4) NOT NULL,
    tenure_months       NUMBER(4) NOT NULL,
    disbursement_date   DATE,
    maturity_date       DATE,
    loan_status         VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
    closure_date        DATE,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_loan_borrower
        FOREIGN KEY (borrower_id)
        REFERENCES BORROWERS(user_id),

    CONSTRAINT fk_loan_rule
        FOREIGN KEY (rule_id)
        REFERENCES LOAN_PRODUCT_RULE(rule_id),

    CONSTRAINT chk_loan_principal
        CHECK (principal_amount > 0),

    CONSTRAINT chk_loan_outstanding
        CHECK (outstanding_amount >= 0),

    CONSTRAINT chk_loan_interest
        CHECK (interest_rate >= 0),

    CONSTRAINT chk_loan_tenure
        CHECK (tenure_months > 0),

    CONSTRAINT chk_loan_status
        CHECK (loan_status IN
            ('PENDING', 'ACTIVE', 'CLOSED', 'DEFAULTED', 'CANCELLED'))
);
