CREATE TABLE COOLING_OFF_REQUEST ( 

    EXIT_REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 

    LOAN_ID NUMBER NOT NULL, 

    OFFICER_ID NUMBER, 

    REQUEST_DATE DATE DEFAULT SYSDATE NOT NULL, 

    EXPIRY_DATE DATE, 

    STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL, 

    REASON VARCHAR2(1000), 

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, 

  

    CONSTRAINT FK_COOLING_LOAN 

    FOREIGN KEY (LOAN_ID) 

    REFERENCES LOAN_ACCOUNT(LOAN_ID), 

  

    CONSTRAINT FK_COOLING_OFFICER 

    FOREIGN KEY (OFFICER_ID) 

    REFERENCES OFFICER(OFFICER_ID), 

  

    CONSTRAINT CHK_COOLING_STATUS 

    CHECK (STATUS IN ( 

        'PENDING', 

        'UNDER_REVIEW', 

        'APPROVED', 

        'REJECTED', 

        'CANCELLED', 

        'EXPIRED', 

        'COMPLETED' 

    )), 

  

    CONSTRAINT CHK_COOLING_EXPIRY 

    CHECK ( 

        EXPIRY_DATE IS NULL 

        OR EXPIRY_DATE >= REQUEST_DATE 

    ) 

); 

  

CREATE INDEX IDX_COOLING_LOAN 

ON COOLING_OFF_REQUEST (LOAN_ID); 

  

CREATE INDEX IDX_COOLING_OFFICER 

ON COOLING_OFF_REQUEST (OFFICER_ID); 

  

CREATE INDEX IDX_COOLING_STATUS 

ON COOLING_OFF_REQUEST (STATUS); 

  

