CREATE TABLE COLLATERAL_RELEASE_REQUESTS(
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COLLATERAL_ID NUMBER NOT NULL,
    LOAN_ACCOUNT_ID NUMBER NOT NULL,
    REQUESTED_BY NUMBER NOT NULL,
    ASSIGNED_TO NUMBER,
    STATUS VARCHAR(30) DEFAULT 'PENDIND' NOT NULL,
    REASON VARCHAR(1000),
    EXPECTED_RELEASE_DATE DATE,
    RELEASED_AT TIMESTAMP,
    RELEASE_REFERENCE VARCHAR(100),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_RELEASE_COLLATERAL
    FOREIGN KEY (COLLATERAL_ID)
    REFERENCES COLLATERAL(COLLATERAL_ID),
    
    
    CONSTRAINT CHK_RELEASE_STATUS CHECK ( 
    STATUS IN 
    ('PENDING', 'UNDER_REVIEW', 'INFO_REQUIRED','APPROVED', 'RELEASE_IN_PROGRESS','RELEASE_DELAYED', 'REJECTED', 'RELEASED')

    )
);

CREATE INDEX IDX_RELEASE_LOAN
ON COLLATERAL_RELEASE_REQUESTS (LOAN_ACCOUNT_ID);

CREATE INDEX IDX_RELEASE_STATUS
ON COLLATERAL_RELEASE_REQUESTS (STATUS);

