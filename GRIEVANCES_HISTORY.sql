CREATE TABLE GRIEVANCES_HISTORY (
    HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GRIEVANCE_ID NUMBER NOT NULL,
    OLD_STATUS VARCHAR2(20),
    NEW_STATUS VARCHAR2(20) NOT NULL,
    ACTION_REMARKS VARCHAR2(1000) NOT NULL,
    ACTION_BY NUMBER NOT NULL,
    ACTION_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_GRIEVANCES_HISTORY
        FOREIGN KEY (GRIEVANCE_ID)
        REFERENCES GRIEVANCES (GRIEVANCE_ID),

    CONSTRAINT CHK_GRIEVANCES_HISTORY_STATUS CHECK (
        NEW_STATUS IN (
            'OPEN', 'IN_PROGRESS', 'RESOLVED',
            'ESCALATED', 'CLOSED'
        )
    )
);

CREATE INDEX IDX_GRIEVANCE_HISTORY_ID
ON GRIEVANCES_HISTORY(GRIEVANCE_ID, ACTION_AT);