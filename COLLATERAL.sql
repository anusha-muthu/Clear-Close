CREATE TABLE COLLATERAL(
    COLLATERAL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOAN_ACCOUNT_ID NUMBER NOT NULL,
    COLLATERAL_TYPE VARCHAR(30)NOT NULL,
    DESCRIPTION VARCHAR(500),
    CUSTODIAN VARCHAR(100),
    RELEASE_STATUS VARCHAR(30) DEFAULT 'NOT ELIGIBLE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_COLLATERAL_STATUS CHECK(
        RELEASE_STATUS IN(
        'NOT_ELIGIBLE','ELIGIBLE','RELEASE_PENDING','RELEASED'
        )
    ),
    CONSTRAINT FK_COLLATERAL_LOAN
    FOREIGN KEY (LOAN_ACCOUNT_ID)
    REFERENCES LOAN_ACCOUNT(LOAN_ID)
);

